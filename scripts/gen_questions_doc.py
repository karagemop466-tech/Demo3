"""
gen_questions_doc.py — render docs/questions.md from data/questions.json.

Single source of truth: the JSON. The markdown is generated so the docs and the site can never
disagree about what is known, what is missing, or which question blocks which requirement.
"""
from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "questions.json")
OUT = os.path.join(ROOT, "docs", "questions.md")


def main() -> int:
    with open(SRC) as fh:
        doc = json.load(fh)
    qs = doc["questions"]
    blocking = [q for q in qs if q.get("blocking")]
    lines = [
        "# Open questions — known vs missing",
        "",
        f"Generated by `scripts/gen_questions_doc.py` from `data/questions.json` "
        f"({len(qs)} questions, {len(blocking)} blocking) at "
        f"{doc['_meta']['generated_at_utc']}. Edit the JSON, not this file.",
        "",
        "> " + doc["_meta"]["rule"],
        "",
        "## Index",
        "",
        "| ID | Question | Blocks | Affects |",
        "|---|---|---|---|",
    ]
    for q in qs:
        lines.append(f"| [{q['id']}](#{q['id'].lower()}) | {q['question']} | "
                     f"{'**yes**' if q.get('blocking') else 'no'} | {', '.join(q.get('affects', []))} |")
    lines += ["", "## Requirement impact", "",
              "| Requirement | Status | Gated by |", "|---|---|---|"]
    for q in qs:
        for a in q.get("affects", []):
            if q.get("blocking"):
                lines.append(f"| {a} | blocked until answered | {q['id']} |")
    lines += ["", "---", ""]
    for q in qs:
        lines += [f"## {q['id']}", "", "### " + q["question"], "",
                  "**Why it matters.** " + q["why_it_matters"], "",
                  "**Known (verified).**", ""]
        for k in q.get("known", []):
            lines.append("- " + k)
        lines += ["", "**Missing.** " + q["missing"], "",
                  "**How to find out.** " + q["how_to_find_out"], "",
                  "**Suggestion.** " + q["suggestion"], "",
                  "**Sources.**"]
        for s in q.get("sources", []):
            lines.append(f"- <{s}>")
        lines.append("")
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines).rstrip() + "\n")
    print(f"docs/questions.md written: {len(qs)} questions, {len(blocking)} blocking, {os.path.getsize(OUT)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
