#!/usr/bin/env python3
"""Validate the Kalshi Demo Tracker (docs/tracker/) before publishing.

Checks:
  1. Every JSON data file parses.
  2. Every data row (series, events, markets, orderbooks, flags, sources) has an https source link.
  3. Every internal link and asset reference in every HTML page resolves to a file in docs/.
  4. Every page is generated by scripts/tracker_build.py (no orphan pages).
Exit code 1 if any check fails.
"""
import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs" / "tracker"
errors = []


def err(msg):
    errors.append(msg)


# 1 + 2: JSON and source links
data = {}
for p in sorted((DOCS / "data").glob("*.json")):
    try:
        data[p.name] = json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        err(f"{p.relative_to(ROOT)}: invalid JSON: {e}")

snap = data.get("snapshot.json", {})
for key in ("series", "events", "markets"):
    for i, row in enumerate(snap.get(key, [])):
        src = row.get("source_api", "")
        if not src.startswith("https://"):
            err(f"snapshot.json {key}[{i}] {row.get('ticker')}: missing https source_api")
        if "verified" not in row:
            err(f"snapshot.json {key}[{i}] {row.get('ticker')}: missing 'verified'")
for i, ob in enumerate(snap.get("orderbooks", [])):
    if not ob.get("captured_from", "").startswith("https://"):
        err(f"snapshot.json orderbooks[{i}]: missing https captured_from")

for f in data.get("flags.json", {}).get("flags", []):
    if not f.get("source", "").startswith("https://"):
        err(f"flags.json {f.get('id')}: missing https source")
for s in data.get("sources.json", {}).get("sources", []):
    if not s.get("url", "").startswith("https://"):
        err(f"sources.json {s.get('id')}: missing https url")

print(
    "data rows:",
    {
        "series": len(snap.get("series", [])),
        "events": len(snap.get("events", [])),
        "markets": len(snap.get("markets", [])),
        "flags": len(data.get("flags.json", {}).get("flags", [])),
        "questions": len(data.get("questions.json", {}).get("questions", [])),
        "suggestions": len(data.get("suggestions.json", {}).get("suggestions", [])),
    },
)


# 3: internal links
class Refs(HTMLParser):
    def __init__(self):
        super().__init__()
        self.refs = []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        for k in ("href", "src"):
            v = a.get(k)
            if v:
                self.refs.append(v)


pages = sorted(DOCS.rglob("*.html"))
for page in pages:
    parser = Refs()
    parser.feed(page.read_text(encoding="utf-8"))
    for ref in parser.refs:
        if re.match(r"^(https?:|mailto:|#|data:)", ref):
            continue
        target = (page.parent / ref.split("#")[0].split("?")[0]).resolve()
        if ref.split("#")[0] == "":
            continue
        if not target.exists():
            err(f"{page.relative_to(ROOT)}: broken link -> {ref}")

# 4: every page is generated
build = (ROOT / "scripts" / "tracker_build.py").read_text(encoding="utf-8")
for page in pages:
    rel = page.relative_to(DOCS).as_posix()
    if rel not in build:
        err(f"{page.relative_to(ROOT)}: not produced by scripts/tracker_build.py")

print("html pages:", len(pages))
if errors:
    print(f"FAILED: {len(errors)} problem(s)")
    for e in errors:
        print(" -", e)
    sys.exit(1)
print("OK: JSON valid, every row has a source link, no broken internal links.")
