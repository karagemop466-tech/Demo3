#!/usr/bin/env python3
"""Offline verification gate for the Kalshi demo alert dashboard."""
from __future__ import annotations

import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
ALERTS = ROOT / "data" / "alerts"


def check_json_files() -> None:
    required = {
        "alerts.json": ("updated_at", "threshold_dollars", "alerts"),
        "resolutions.json": ("count", "by_market"),
        "orderbooks.json": ("count", "orderbooks"),
        "prices.json": ("updated_at", "markets"),
        "status.json": ("api_root",),
    }
    for filename, keys in required.items():
        path = ALERTS / filename
        if not path.exists():
            continue  # clean checkout has only .gitkeep until workflow's first run
        data = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(data, dict):
            raise AssertionError(f"{path}: expected a JSON object")
        for key in keys:
            if key not in data:
                raise AssertionError(f"{path}: missing top-level {key}")
        if filename == "alerts.json":
            if float(data["threshold_dollars"]) != 0.10:
                raise AssertionError("alerts.json threshold must be exactly $0.10")
            for i, alert in enumerate(data["alerts"]):
                if not isinstance(alert, dict) or not alert.get("source_url"):
                    raise AssertionError(f"alerts.json alerts[{i}] missing source_url")
                if not alert.get("prev_source_url"):
                    raise AssertionError(f"alerts.json alerts[{i}] missing prev_source_url")
        if filename == "prices.json":
            for ticker, market in data["markets"].items():
                for i, point in enumerate(market.get("points", [])):
                    if not point.get("source_url"):
                        raise AssertionError(f"prices {ticker} points[{i}] missing source_url")
        if filename == "resolutions.json":
            by_market = data["by_market"]
            entries = by_market.values() if isinstance(by_market, dict) else by_market
            for i, row in enumerate(entries):
                if row.get("result") in ("yes", "no") and not row.get("source_url"):
                    raise AssertionError(f"resolution row {i} missing source_url")


def main() -> int:
    subprocess.run(["node", "--check", "assets/alerts.js"], cwd=ROOT, check=True)
    # Compile without leaving generated bytecode in the source tree.
    for path in (ROOT / "automation").rglob("*.py"):
        compile(path.read_text(encoding="utf-8"), str(path), "exec")
    check_json_files()
    html = (ROOT / "alerts.html").read_text(encoding="utf-8")
    js = (ROOT / "assets" / "alerts.js").read_text(encoding="utf-8")
    assert re.search(r"threshold_dollars\s*[=:]\s*0?\.10|THRESHOLD\s*=\s*0?\.10", js), \
        "alert threshold $0.10 not present in client"
    assert 'id="bodyAll"' in html and 'id="bodyRoi"' in html, "two feeds required"
    assert 'id="priceChart"' in html and 'id="depthChart"' in html, "price/depth charts required"
    print("alerts verification: JS syntax, Python compile, JSON schemas, source URLs, and $0.10 threshold OK")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"alerts verification failed: {exc}", file=sys.stderr)
        raise
